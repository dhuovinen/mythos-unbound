/**
 * Norse pantheon roster and genealogy graph.
 *
 * The second pantheon exists to make cross-pantheon play real: relations resolve only within a
 * pantheon, so a Norse unit facing a Greek one is a pure statistics fight — un-counterable, and
 * unbuffed. That rule was built and tested from the start; until now there was simply nothing to
 * cross to.
 *
 * Norse is deliberately the darker graph. Where Greek relations are mostly hierarchy and grudge,
 * Norse is saturated with mutual destruction: Thor and Jörmungandr kill each other, Heimdall and
 * Loki kill each other, Baldr's killer is himself killed in revenge. Note there is no `devourer`
 * here — no Norse parent turns on their children the way Cronus does, so Reluctance applies
 * normally across the board. That is a real difference in how the two pantheons play.
 */

